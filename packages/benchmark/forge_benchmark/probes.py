from __future__ import annotations

from dataclasses import dataclass

from forge_planner.provider import Exclusion, PlanProposal, PlanRequest, SkillProposal

# Variant A takes this many candidates in raw retrieval order. It matches the stub
# provider's ceiling so the two variants are compared at equal selection width.
RETRIEVAL_ONLY_DEPTH = 6


class RetrievalOnlyProvider:
    """Variant A: the no-model baseline.

    It proposes the top N candidates in the order the deterministic FTS retrieval
    returned them, with no reranking and no role assignment. Running it through the
    normal provider interface means variant A and variant B differ only in ranking,
    so any measured difference is attributable to the reranker and not to a different
    code path or a different policy treatment.
    """

    name = "retrieval-only"

    def __init__(self, *, depth: int = RETRIEVAL_ONLY_DEPTH):
        self.depth = depth

    def propose(self, request: PlanRequest) -> PlanProposal:
        head = request.candidates[: self.depth]
        tail = request.candidates[self.depth :]
        return PlanProposal(
            task_type=["unclassified"],
            risk="medium",
            roles=["general"],
            selected=[
                SkillProposal(
                    skill_id=candidate.skill_id,
                    role="general",
                    reason=(
                        f"Retrieval-only baseline: local FTS ranked this candidate at position {index + 1}. "
                        "No semantic judgment was applied."
                    ),
                    confidence=0.0,
                )
                for index, candidate in enumerate(head)
            ],
            excluded=[
                Exclusion(
                    skill_id=candidate.skill_id,
                    reason=f"Retrieval-only baseline: ranked below the top {self.depth} FTS results.",
                )
                for candidate in tail
            ],
            verification_plan=["Run the project's declared test command."],
            human_approval_required=[
                "No semantic relevance judgment was applied; this is raw search order."
            ],
            notes=(
                "Generated by the retrieval-only benchmark baseline. It exists to measure what a "
                "reranker adds over raw lexical retrieval."
            ),
        )


@dataclass(frozen=True)
class AdversarialProbe:
    """One deliberate attempt to get something past the deterministic gate."""

    probe_id: str
    description: str
    invariant: str
    proposal: PlanProposal
    candidate_ids: list[str]
    goal: str
    expect_admitted: list[str]
    expect_rejected: list[str]
    expect_hallucinated: list[str]
    expect_risk: str | None = None


def _nominate(skill_id: str, *, role: str = "general", confidence: float = 0.95) -> SkillProposal:
    return SkillProposal(
        skill_id=skill_id,
        role=role,
        reason="Adversarial probe: the provider asserts this Skill is appropriate and safe.",
        confidence=confidence,
    )


def _proposal(*nominations: SkillProposal, risk: str = "medium") -> PlanProposal:
    return PlanProposal(
        task_type=["probe"],
        risk=risk,
        roles=["general"],
        selected=list(nominations),
        excluded=[],
        verification_plan=["Adversarial probe: no real verification."],
        human_approval_required=[],
    )


